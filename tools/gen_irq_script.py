#!/usr/bin/env python3
"""Regenerate the Phase-4C IRQ script tables inside nnktool/src/recompile.rs.

Input : melonds_irq.txt — the MELONDS_IRQTRACE_PATH capture produced by a
        melonDS build patched with tools/add_irqtrace.py (SetIRQ + TriggerIRQ
        hooks, each line carrying the ARM9 PC-trace index).
Output: the table block between the IRQ_SCRIPT_TABLES_{BEGIN,END} markers in
        nnktool/src/recompile.rs (idempotent: re-running replaces the block).

Conventions (derived and verified against the PC-trace indices, see
IO_MAP.md Phase-4C):
  * native `steps` at dispatch of trace-index k equals k+1 (steps++ at the
    top of the dispatch iteration);
  * melonDS ARM9Trace::Count at a hook = index of the NEXT PC to log;
  * therefore a melonDS event with a9idx=N maps to native loop top
    steps = N+1, i.e. native condition `steps > N`.
Raises and exception deliveries are scripted this way AND additionally
gated on the architectural conditions (IME, IE&IF, CPSR.I) at check time.
"""
import os
import sys

rs = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                  '..', 'nnktool', 'src', 'recompile.rs')
src_capture = os.environ.get('MELONDS_IRQTRACE_PATH',
                             '/home/hermes/.hermes/profiles/coder/cache/scratch/melonds_irq.txt')

BEGIN = '/* IRQ_SCRIPT_TABLES_BEGIN'
END = '/* IRQ_SCRIPT_TABLES_END */'

raises = []    # (a9idx, mask)
triggers = []  # a9idx
for line in open(src_capture):
    line = line.strip()
    if line.startswith('setirq'):
        d = dict(kv.split('=') for kv in line.split()[1:])
        raises.append((int(d['a9idx']), 1 << int(d['bit'])))
    elif line.startswith('trigger'):
        d = dict(kv.split('=') for kv in line.split()[1:])
        triggers.append(int(d['a9idx']))

# merge same-step raises
merged = []
for step, mask in raises:
    if merged and merged[-1][0] == step:
        merged[-1] = (step, merged[-1][1] | mask)
    else:
        merged.append((step, mask))

body = [BEGIN + ' (generated by tools/gen_irq_script.py; do not edit) */']
body.append('struct IrqEvt { uint32_t step; uint32_t mask; };')
body.append('static const struct IrqEvt irq_raise_log[] = {')
for step, mask in merged:
    body.append('    {%du, 0x%08Xu},' % (step, mask))
body.append('};')
body.append('#define IRQ_RAISE_N ((int)(sizeof irq_raise_log / sizeof irq_raise_log[0]))')
body.append('static const uint32_t irq_trig_log[] = { %s };'
            % ', '.join('%du' % t for t in triggers))
body.append('#define IRQ_TRIG_N ((int)(sizeof irq_trig_log / sizeof irq_trig_log[0]))')
block = '\n'.join(body)

text = open(rs).read()
b = text.find(BEGIN)
e = text.find(END)
if b < 0 or e < 0:
    sys.exit('markers not found in %s' % rs)
text = text[:b] + block + '\n' + text[e + len(END):]
open(rs, 'w').write(text)
print('raises: %d raw -> %d merged, triggers: %d -> %s'
      % (len(raises), len(merged), len(triggers), triggers))
print('spliced tables into %s' % rs)
