#!/usr/bin/env python3
"""Splice the Phase-5B ARM7 keypad-publish call into an ALREADY-GENERATED image.

    python3 tools/p5b_arm7_keypad.py <in_image.c> <out_image.c>

The implementation lives in `tools/nnk_smc.inc` (`arm7_publish_keypad`), which
the dispatch image pulls in with `#include "nnk_smc.inc"`.  The only thing the
image itself must carry is the per-dispatch call in `trace_pc`.  Images
regenerated by `nnktool recompile-all` (nnktool/src/recompile.rs) already emit
it; this patcher exists because the frozen Phase-3A image
(`work/phase3a/arm9_thumb_ovl_itcm_p4j.c`) carries the Thumb dispatch, overlay
unions and ITCM cases that the seed tables do not reproduce byte-for-byte
(see tools/p4v_fix_umull.py, tools/p5b_store_watch.py).

Idempotent: refuses to run twice on the same image.

WHY (measured, melonDS `p5b_mel_top2.txt`): the ARM7 publishes W16 0x2C00 to
main-RAM 0x3FFFA8 every ~267,000 cycles.  The ARM9's keypad edge detector at
0x02049B0C ORs that word into its KEYINPUT read; with the word left at 0 the
derived key state is 0x2C00 instead of 0, and 0x02049BDC branches the wrong
way.  Without this call the native run can never see the published word.
"""
import sys

ANCHOR = '    cycles++;                       /* coarse timing: ~1 cycle per instruction */\n'
CALL = ('    /* Phase-5B: the ARM7\'s periodic keypad/touch publish (nnk_smc.inc). */\n'
        '    { extern void arm7_publish_keypad(void); arm7_publish_keypad(); }\n')


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src, dst = sys.argv[1], sys.argv[2]
    s = open(src).read()
    if 'arm7_publish_keypad' in s:
        sys.exit('image already carries the ARM7 keypad publish')
    if s.count(ANCHOR) != 1:
        sys.exit('trace_pc cycles++ anchor count %d' % s.count(ANCHOR))
    s = s.replace(ANCHOR, ANCHOR + CALL, 1)
    open(dst, 'w').write(s)
    print('wrote %s (ARM7 keypad publish call inserted)' % dst)


if __name__ == '__main__':
    main()
