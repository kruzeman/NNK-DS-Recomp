#!/usr/bin/env python3
"""Phase-5O: splice the BLX-immediate interworking note into a FROZEN image.

    python3 tools/p5o_blx_note.py <in_image.c> <out_image.c> \
            --img "0x02000000:work/ghidra_src/arm9.bin,0x020C0000:work/phase3a/ovl_p4f4.bin"

WHY: the image under test is a Phase-4F build artifact (`arm9_thumb_ovl_itcm_*.c`)
that cannot be regenerated byte-for-byte, so every emitter change has to be
spliced into it (the Phase-5J/5K precedent).  The emitter fix for this class is
in `nnktool/src/recompile.rs` `Kind::BlxImm`, global branch:

    let raw = if thumb { *target & !1u } else { *target | 1u };
    nnk_smc_note_branch(0x..................);   /* before: pc = target & !1 */

`blx <imm>` ALWAYS switches instruction state (ARM ARM A7.1.4): the Thumb pair
targets ARM, the ARM form targets Thumb.  The note is what the live re-decoder
uses for the ONE dispatch that follows (`smc_carried_thumb`, Phase-5C); without
it an unrooted callee is decoded in whatever state the map/register/sticky
guess last held.

Measured (barrier I3): `0x020F6ED6 blx 0x02054144` (Thumb halfwords 0xF75D
0xE936) left the sticky state Thumb, so the live decoder re-decoded the ARM
`push {r4,lr}` at 0x02054144 as Thumb, ran 0x02054146..0x020541BE through the
ARM bytes and branched into the MIDDLE of the movie-player table generator at
0x02054764 (prologue skipped).  Its 5th argument is reloaded from
[[sp,#0x128]]; that slot held 1 instead of a destination pointer, so
`str r0,[r1,r7,lsl #2]` with r7=0x14 stored to guest address 0x51 ==
ITCM[0x51..0x54] and zeroed the IRQ dispatcher's literal pool 0x01FF8050/4
(Phase-5N mechanism).

The state of the SITE is taken from the generation-0 image word at the case
address, never guessed:

    ARM   cond=1111, bits 27..25 = 101, bit24 = H   (`0xFA......`)
    Thumb halfword pair h1 in 0xF000..0xF7FF, h2 in 0xE800..0xEFFF
          (suffix 11101 = BLX; suffix 11111 is BL and stays in Thumb)

Idempotent: a site that already carries its note is counted and skipped.
"""
import re
import sys

CASE = re.compile(r'^\s*case 0x([0-9A-Fa-f]{8})u:')
BLX_COMMENT = re.compile(r'^\s*/\* 0x([0-9A-Fa-f]{8}): blx 0x([0-9A-Fa-f]{8}) \*/\s*$')
PC_ASSIGN = re.compile(r'^(\s*)pc = 0x([0-9A-Fa-f]{8})u;\s*$')
NOTE = re.compile(r'^\s*nnk_smc_note_branch\(0x([0-9A-Fa-f]{8})u\);\s*$')


def load_segments(spec):
    segs = []
    for part in (spec or '').split(','):
        part = part.strip()
        if not part:
            continue
        addr, path = part.split(':', 1)
        segs.append((int(addr, 0), open(path, 'rb').read()))
    return segs


def word_at(segs, addr):
    for base, data in segs:
        if base <= addr and addr + 4 <= base + len(data):
            o = addr - base
            return data[o] | (data[o + 1] << 8) | (data[o + 2] << 16) | (data[o + 3] << 24)
    return None


def site_state(w):
    """'arm' / 'thumb' for a BLX-immediate site, None if the word is neither."""
    if w is None:
        return None
    if (w & 0xFE000000) == 0xFA000000:            # ARM BLX(imm)
        return 'arm'
    h1 = w & 0xFFFF
    h2 = (w >> 16) & 0xFFFF
    if (h1 & 0xF800) == 0xF000 and (h2 & 0xF800) == 0xE800:
        return 'thumb'                            # Thumb BLX(1) pair
    return None


def main(argv):
    if len(argv) < 3:
        print(__doc__)
        return 2
    src_path, dst_path = argv[1], argv[2]
    spec = None
    check = False
    i = 3
    while i < len(argv):
        if argv[i] == '--img':
            spec = argv[i + 1]
            i += 2
        elif argv[i] == '--check':
            check = True
            i += 1
        else:
            print('unknown argument %s' % argv[i])
            return 2
    if not spec:
        print('--img "addr:path[,addr:path]" is required')
        return 2
    segs = load_segments(spec)

    lines = open(src_path).read().splitlines(True)
    out = []
    cur_case = None
    pending = None          # (case addr, target) of the blx comment just seen
    noted = skipped = unknown = none_found = 0
    for idx, ln in enumerate(lines):
        mc = CASE.match(ln)
        if mc:
            cur_case = int(mc.group(1), 16)
            pending = None
        mb = BLX_COMMENT.match(ln)
        if mb:
            assert int(mb.group(1), 16) == cur_case, 'comment/case mismatch at %s' % ln.strip()
            pending = (cur_case, int(mb.group(2), 16))
            out.append(ln)
            continue
        mp = PC_ASSIGN.match(ln)
        if pending is not None and mp and int(mp.group(2), 16) == pending[1]:
            addr, target = pending
            st = site_state(word_at(segs, addr))
            if st is None:
                unknown += 1
                print('WARN: no BLX encoding at 0x%08X (case word does not match)' % addr)
            else:
                raw = (target & ~1) if st == 'thumb' else (target | 1)
                out.append(ln)
                nxt = lines[idx + 1] if idx + 1 < len(lines) else ''
                mn = NOTE.match(nxt)
                if mn and int(mn.group(1), 16) == raw:
                    skipped += 1
                else:
                    if not check:
                        out.append('%snnk_smc_note_branch(0x%08Xu);\n' % (mp.group(1), raw))
                    noted += 1
                pending = None
                continue
            pending = None
        if pending is not None and 'call_shim' in ln:
            none_found += 1              # shim call: the callee is compiled, no state needed
            pending = None
        out.append(ln)
    if not check:
        open(dst_path, 'w').write(''.join(out))
    print('blx-imm sites noted: %d  already-noted: %d  shim calls: %d  unknown: %d'
          % (noted, skipped, none_found, unknown))
    return 0 if unknown == 0 else 1


if __name__ == '__main__':
    sys.exit(main(sys.argv))
