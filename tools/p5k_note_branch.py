#!/usr/bin/env python3
"""Phase-5K: correct + complete the interworking-state note in a FROZEN image.

    python3 tools/p5k_note_branch.py <in_image.c> <out_image.c> [--check]
                                     [--img "0x02000000:path[,addr:path]"]

WHY: Phase-5J spliced `nnk_smc_note_branch()` into every LDM/`pop {..,pc}` site
of an already-generated image (tools/p5j_note_branch.py), because the image
under test is a Phase-4F build artifact that cannot be regenerated byte-for-byte
and every emitted body must match what the current emitter would produce.  Two
things were wrong with that splice, and both are decode classes (not patches to
the guest):

  F  the single-register form was emitted as `nnk_smc_note_branch(_t | 1u)`
     for EVERY register list, i.e. Thumb semantics (melonDS T_POP:
     `if (cpu->Num==1) pc |= 0x1;`).  The ARM form is the opposite —
     melonDS A_LDM (ARMInterpreter_LoadStore.cpp:436):
     `if (cpu->Num == 1) pc &= ~0x1; JumpTo(pc);`.  Measured consequence:
     the ARM epilogue `add sp,#12; pop {pc}` at 0x02043C00/0x02043C04 returned
     to the ARM code at 0x0207D2D8 tagged Thumb, the live re-decoder ran that
     ARM function as Thumb, walked 0x0207E828.. through the guest's own string
     table and the ASCII word 0x49552F61 at 0x0207E94C decoded as an ARM
     `ldmia` whose r13 list slot loaded 0 from the string bytes -> sp = 0, halt
     at 0x0207EA20 (42,038,854 steps).

  G  compiled `bx`/`blx Rm` sites carried no state at all
     (`pc = _t & ~1u; }`): the target's bit0 is the only record of the state it
     must be decoded in, and melonDS BX/BLX_REG both `JumpTo(Rm)` (bit0).  The
     emitter (nnktool/src/recompile.rs Kind::Bx) now emits the note for both
     the register-indirect and the `bx lr` return forms; this tool splices the
     same text into the frozen image.

The state a single-register LDM site must use is decided from the COMPILED
GENERATION word at that address (the generation-0 segments the runtime compares
against, NNK_SMC_IMAGE format):
    ARM   `cond 100 P U S W L Rn list` (bits 27..25 = 100, bit20 L, bit15 pc)
    Thumb `1011 110 L list`  (0xBC00..0xBDFF, bit8 = pc)
An address whose word matches BOTH, or NEITHER, is reported and left untouched
- this tool never guesses.  LDR-pc sites are deliberately left alone: melonDS
A_LDR0 masks bit0 and does NOT interwork.

Idempotent: a site that already carries the right note is counted and skipped.
"""
import os
import re
import sys

STATE_POP = re.compile(r'^(\s*)nnk_smc_note_branch\(_t (\| 1u|& ~1u)\);\s*$')
PC_ASSIGN = re.compile(r'^(\s*)pc = _t & ~1u;\s*$')
LOAD_A = re.compile(r'^\s*uint32_t _t = ld32\(_a \+ \d+u\);')
BX_OPEN = re.compile(r'^\s*\{ uint32_t _t = r\[[^\]]+\];\s*$')
BX_SAME_LINE = re.compile(r'^(\s*)pc = _t & ~1u; \}\s*$')
CASE = re.compile(r'^\s*case 0x([0-9A-Fa-f]{8})u:')


def load_segments(spec):
    segs = []
    for part in (spec or '').split(','):
        part = part.strip()
        if not part:
            continue
        addr, _, path = part.partition(':')
        with open(path, 'rb') as fh:
            segs.append((int(addr, 0), fh.read()))
    return segs


def word_at(segs, addr, width=4):
    for base, data in segs:
        off = addr - base
        if 0 <= off and off + width <= len(data):
            return int.from_bytes(data[off:off + width], 'little')
    return None


def ldm_form(w):
    """'arm' / 'thumb' / None (ambiguous or uncovered) for an LDM-pc site."""
    arm = ((w >> 28) != 0xF and (w & 0x0E000000) == 0x08000000 and
           (w & 0x00100000) != 0 and (w & 0x00008000) != 0)
    thumb = ((w & 0xFE00) == 0xBC00 and (w & 0x0100) != 0)
    hw2 = w >> 16
    thumb2 = ((hw2 & 0xFE00) == 0xBC00 and (hw2 & 0x0100) != 0)
    if arm and not (thumb or thumb2):
        return 'arm'
    if (thumb or thumb2) and not arm:
        return 'thumb'
    return None


def main(argv):
    if len(argv) < 3:
        sys.exit(__doc__)
    src, dst = argv[1], argv[2]
    check = '--check' in argv[3:]
    spec = os.environ.get('NNK_SMC_IMAGE', '')
    for i, a in enumerate(argv[3:]):
        if a == '--img' and i + 1 < len(argv[3:]):
            spec = argv[3:][i + 1]
        elif a.startswith('--img='):
            spec = a.split('=', 1)[1]
    segs = load_segments(spec)
    if not segs:
        sys.exit('p5k: no image segments (pass --img or set NNK_SMC_IMAGE)')

    lines = open(src).read().split('\n')
    out = []
    addr = None
    fixed = ok = unknown = 0
    bx_added = bx_already = 0
    prev = None
    for i, ln in enumerate(lines):
        m = CASE.match(ln)
        if m:
            addr = int(m.group(1), 16)
        prev2 = lines[i - 2] if i >= 2 else ''
        # ---- F: single-register LDM/pop note must follow the FORM's state ----
        mp = STATE_POP.match(ln)
        if mp and PC_ASSIGN.match(prev or '') and LOAD_A.match(prev2):
            w = word_at(segs, addr, 4) if addr is not None else None
            form = ldm_form(w) if w is not None else None
            if form is None:
                unknown += 1
                out.append(ln)
            else:
                want = '& ~1u' if form == 'arm' else '| 1u'
                if mp.group(2) == want:
                    ok += 1
                    out.append(ln)
                else:
                    out.append('%snnk_smc_note_branch(_t %s);' % (mp.group(1), want))
                    fixed += 1
            prev = ln
            continue
        # ---- G: compiled bx/blx Rm: splice the state note ----
        mb = BX_SAME_LINE.match(ln)
        if mb and BX_OPEN.match(prev or ''):
            out.append('%spc = _t & ~1u;' % mb.group(1))
            out.append('%snnk_smc_note_branch(_t); }' % mb.group(1))
            bx_added += 1
        elif ('nnk_smc_note_branch(_t);' in ln and prev is not None and
              PC_ASSIGN.match(prev)):
            bx_already += 1
            out.append(ln)
        else:
            out.append(ln)
        prev = ln

    text = '\n'.join(out)
    print('%s: LDM single-register -> %d note(s) corrected, %d already right, '
          '%d undecidable (left untouched)'
          % (src, fixed, ok, unknown))
    print('%s: bx/blx Rm -> %d noted, %d already noted'
          % (src, bx_added, bx_already))
    if check:
        return 0 if (fixed == 0 and bx_added == 0) else 1
    if text != open(src).read():
        with open(dst, 'w') as fh:
            fh.write(text)
        print('wrote %s' % dst)
    else:
        print('%s: no change needed' % dst)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
