#!/usr/bin/env python3
"""Phase-5AP: generate the ROM-derived `pc -> form` (Thumb/ARM) map.

WHY
---
Classes 48/49/50 were three point fixes for the same question: in which
processor state does a pc execute that the recompiler did not reach through a
known branch?  The runtime answered it with local guesses and each guess was
wrong once.  This generator answers it from the ROM image, once, for every pc
the guest can execute, and the runtime then uses that answer as the PRIMARY
authority (its own inference stays as a cross-check that must log a
disagreement instead of winning).

WHAT IT DOES
------------
1. Reads the ROM header, decompresses the ARM9 image (Nintendo "code
   compression") and every ARM9 overlay the OVT declares.  No derived file is
   trusted: the input is the .nds image alone.
2. Writes the decompressed images under work/ (never committed) and a manifest
   whose seeds are the ROM's own entry points:
      * ARM9: header entry (0x02000800), ARM state;
      * each overlay: ram base plus its sinit (ctor) array [init_start,
        init_end), whose entries are function pointers (bit0 = Thumb), i.e.
        exactly the interworking rule of `ldm`/`pop {..,pc}`.
3. Runs `nnktool pcform`, which walks the CFG with the recompiler's own
   descent (recover.rs) and adds, each round, every 32-bit pointer in every
   image that targets code not covered yet (bit0 selects the state -- the
   `bx`/`blx rM` rule).  That is how the guest really enters overlay exports
   and vtables.
4. Emits `work/phase5ap/nnk_pcform_map.h` (binary-searchable [lo,hi) runs per
   state) plus a text summary of the entry points and the run counts.

The header is a build artifact: it contains no game bytes, but it is derived
from them, so it lives under the gitignored work/ tree.  This script is the
committed source of truth.

Usage: tools/gen_pcform.py [--rom ROM] [--outdir work/phase5ap]
                           [--tool nnktool/target/release/nnktool]
"""
import argparse
import json
import os
import struct
import sys

SITE = os.path.expanduser("~/.local/lib/python3.12/site-packages")
if os.path.isdir(SITE) and SITE not in sys.path:
    sys.path.insert(0, SITE)
try:
    from ndspy import codeCompression
except Exception as exc:  # pragma: no cover - environment problem
    sys.exit("gen_pcform: ndspy is required for the ROM decompressor: %s" % exc)

ARM9_BASE = 0x02000000


def rd32(buf, off):
    return struct.unpack_from("<I", buf, off)[0]


def decompress(stored, what):
    """Nintendo "code compression" (BLZ); exits on a malformed stream."""
    try:
        return codeCompression.decompress(stored)
    except Exception as exc:
        sys.exit("gen_pcform: %s does not decompress (%s)" % (what, exc))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--rom", default="Ni No Kuni.nds")
    ap.add_argument("--outdir", default="work/phase5ap")
    ap.add_argument("--tool", default="nnktool/target/release/nnktool")
    ap.add_argument("--limit-overlays", type=int, default=0,
                    help="debug: only the first N overlays")
    opts = ap.parse_args()

    if not os.path.exists(opts.rom):
        sys.exit("gen_pcform: missing ROM %s" % opts.rom)
    if not os.path.exists(opts.tool):
        sys.exit("gen_pcform: missing %s (cd nnktool && cargo build --release)"
                 % opts.tool)
    rom = open(opts.rom, "rb").read()

    a9_off, a9_entry, a9_ram, a9_size = struct.unpack_from("<IIII", rom, 0x20)
    ovt_off, ovt_size = struct.unpack_from("<II", rom, 0x50)
    fat_off, fat_size = struct.unpack_from("<II", rom, 0x48)

    imgdir = os.path.join(opts.outdir, "img")
    os.makedirs(imgdir, exist_ok=True)

    fat = [struct.unpack_from("<II", rom, fat_off + 8 * i) for i in range(fat_size // 8)]

    def read_file(fid):
        off, end = fat[fid]
        return rom[off:end]

    # ---- ARM9 (stored compressed)
    stored = rom[a9_off:a9_off + a9_size]
    arm9 = decompress(stored, "ARM9")
    if a9_ram != ARM9_BASE:
        sys.exit("gen_pcform: unexpected ARM9 ram base 0x%08X" % a9_ram)
    arm9_path = os.path.join(imgdir, "arm9.bin")
    open(arm9_path, "wb").write(arm9)

    manifest = []
    entries = []
    manifest.append("# Phase-5AP pc->form manifest (generated by tools/gen_pcform.py)")
    manifest.append("img arm9 0x%08X %s" % (ARM9_BASE, os.path.abspath(arm9_path)))
    manifest.append("seed arm9 0x%08X arm   # ROM header entry" % a9_entry)
    entries.append({"image": "arm9", "kind": "entry", "addr": a9_entry, "form": "arm"})

    # ---- overlays
    n_ovl = ovt_size // 32
    if opts.limit_overlays:
        n_ovl = min(n_ovl, opts.limit_overlays)
    for i in range(n_ovl):
        b = ovt_off + 32 * i
        oid, ram, ram_size, bss, init_lo, init_hi, fid, flags = struct.unpack_from(
            "<IIIIIIII", rom, b)
        stored_ov = read_file(fid)
        compressed = flags >> 24
        ov = decompress(stored_ov, "ov%03d" % oid) if (compressed & 1) else stored_ov
        if len(ov) < ram_size:
            sys.exit("gen_pcform: ov%03d decompressed to %d < ramSize %d"
                     % (oid, len(ov), ram_size))
        ov = ov[:ram_size]
        path = os.path.join(imgdir, "ov%03d.bin" % oid)
        open(path, "wb").write(ov)
        name = "ov%03d" % oid
        manifest.append("img %s 0x%08X %s" % (name, ram, os.path.abspath(path)))
        entries.append({"image": name, "kind": "base", "addr": ram, "form": "auto"})
        # The ctor array is an array of function pointers: bit0 = Thumb, the
        # same interworking rule `pop {..,pc}` applies.  Only entries inside
        # the image are seeds.
        n_ctor = 0
        for a in range(init_lo, init_hi, 4):
            off = a - ram
            if off < 0 or off + 4 > len(ov):
                continue
            p = rd32(ov, off)
            if p == 0:
                continue
            t = p & ~1
            if ram <= t < ram + len(ov):
                manifest.append("seed %s 0x%08X %s   # ctor" %
                                (name, t, "thumb" if p & 1 else "arm"))
                entries.append({"image": name, "kind": "ctor", "addr": t,
                                "form": "thumb" if p & 1 else "arm"})
                n_ctor += 1
        entries.append({"image": name, "kind": "base", "addr": ram,
                        "form": "auto", "ctors": n_ctor,
                        "ram": ram, "size": ram_size, "id": oid,
                        "file_id": fid, "compressed": compressed & 1})

    man_path = os.path.join(opts.outdir, "pcform.manifest")
    os.makedirs(opts.outdir, exist_ok=True)
    with open(man_path, "w") as fh:
        fh.write("\n".join(manifest) + "\n")

    out_h = os.path.join(opts.outdir, "nnk_pcform_map.h")
    cmd = [opts.tool, "pcform", man_path, out_h]
    print("+ " + " ".join(cmd))
    rc = os.spawnv(os.P_WAIT, os.path.abspath(opts.tool), cmd)
    if rc != 0:
        sys.exit("gen_pcform: nnktool pcform failed rc=%d" % rc)

    summary = {
        "rom": os.path.abspath(opts.rom),
        "arm9_entry": a9_entry,
        "arm9_size": len(arm9),
        "overlays": n_ovl,
        "entries": entries,
        "map": os.path.abspath(out_h),
    }
    with open(os.path.join(opts.outdir, "pcform_summary.json"), "w") as fh:
        json.dump(summary, fh, indent=1)
    print("gen_pcform: %d images, %d declared entries -> %s"
          % (1 + n_ovl, len(entries), out_h))


if __name__ == "__main__":
    main()
